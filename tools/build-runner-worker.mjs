#!/usr/bin/env node
/**
 * Phase v2-07 — build `src/runner/worker.ts` into the runtime bucket.
 *
 * The runner's worker bundles the Clang-on-wasm client and the WASI shim, and
 * that is ~1.3 MB of JavaScript (≈270 kB gzip). The app shell is frozen at
 * 388 kB gzip with ~2 kB of headroom (owner decision, 2026-11-04), so this file
 * must never be part of the entry/precache bundle: it is a **runtime asset**,
 * fetched on demand exactly like the compiler it drives, and cached by the
 * Service Worker's `dsa-archive-runtime-v1` bucket afterwards.
 *
 * Vite cannot emit it there — a `new Worker(new URL(...))` reference would land
 * in `dist/assets/` and be precached — so it is built here, by esbuild, into
 * `public/runtime/runner/worker-<hash>.js`, and `build`/`dev` run this first
 * (see the `prebuild` / `predev` scripts). `index.json` is the app's pointer to
 * the hashed name, so a rebuild can never be served stale from a cache.
 *
 *   node tools/build-runner-worker.mjs            build + write index.json
 *   node tools/build-runner-worker.mjs --check    assert the built file exists
 */
import { createHash } from 'node:crypto'
import { mkdir, readFile, readdir, rm, writeFile } from 'node:fs/promises'
import path from 'node:path'
import process from 'node:process'
import { build } from 'esbuild'

const ROOT = path.resolve(import.meta.dirname, '..')
const OUT_DIR = path.join(ROOT, 'public', 'runtime', 'runner')
const INDEX = path.join(OUT_DIR, 'index.json')

export async function buildRunnerWorker({ quiet = false } = {}) {
  await mkdir(OUT_DIR, { recursive: true })
  const temporary = path.join(OUT_DIR, '.worker.partial.js')
  await build({
    absWorkingDir: ROOT,
    entryPoints: [path.join(ROOT, 'src', 'runner', 'worker.ts')],
    outfile: temporary,
    bundle: true,
    format: 'esm',
    platform: 'browser',
    target: 'es2022',
    minify: true,
    // The bundle is served from our own origin: no `//# sourceURL` noise, but
    // third-party licence text is preserved (MIT/Apache-2.0 with LLVM exception).
    legalComments: 'eof',
    define: { 'process.env.NODE_ENV': '"production"' },
    logLevel: 'warning',
  })
  // We redistribute this bundle from our own origin, so the licences of the
  // code inside it travel with it (and a pointer to the full notices).
  const banner =
    '/*! DSA Archive local code runner (phase v2-07). Bundles @live-codes/clang-wasm@0.3.0 (MIT), ' +
    '@wasm-idle/llvm-core@1.3.0 (MIT AND Apache-2.0 WITH LLVM-exception) and ' +
    '@bjorn3/browser_wasi_shim (MIT). Full notices: docs/THIRD-PARTY-NOTICES.md */\n'
  const bundled = await readFile(temporary, 'utf8')
  const built = Buffer.from(banner + bundled, 'utf8')
  await rm(temporary, { force: true })
  const hash = createHash('sha256').update(built).digest('hex').slice(0, 12)
  const fileName = `worker-${hash}.js`

  // Drop older hashes: a worker that is no longer referenced only wastes the
  // cache the learner paid for.
  for (const entry of await readdir(OUT_DIR).catch(() => [])) {
    if (entry.startsWith('worker-') && entry !== fileName) await rm(path.join(OUT_DIR, entry), { force: true })
  }
  await writeFile(path.join(OUT_DIR, fileName), built)
  const document = {
    schemaVersion: 1,
    note: 'Generated by tools/build-runner-worker.mjs — never edit by hand.',
    worker: `runtime/runner/${fileName}`,
    bytes: built.byteLength,
    hash,
  }
  await writeFile(INDEX, `${JSON.stringify(document, null, 2)}\n`)
  if (!quiet) {
    console.log(`Runner worker: public/runtime/runner/${fileName} · ${(built.byteLength / 1000).toFixed(0)} kB raw`)
  }
  return document
}

/** `--check`: the app needs this file at runtime; a missing one is a build bug. */
export async function checkRunnerWorker() {
  const problems = []
  let index = null
  try {
    index = JSON.parse(await readFile(INDEX, 'utf8'))
  } catch {
    problems.push('public/runtime/runner/index.json is missing — run `npm run runtime:worker`')
  }
  if (index) {
    const file = path.join(ROOT, 'public', path.sep, index.worker)
    try {
      const bytes = await readFile(file)
      if (bytes.byteLength !== index.bytes) {
        problems.push(`${index.worker} is ${bytes.byteLength} B, index.json says ${index.bytes} B`)
      }
      if (!bytes.subarray(0, 512).toString('utf8').startsWith('/*! DSA Archive local code runner')) {
        problems.push(`${index.worker} should start with the bundled third-party licence banner`)
      }
    } catch {
      problems.push(`${index.worker} is missing`)
    }
  }
  return problems
}

async function main() {
  if (process.argv.includes('--check')) {
    const problems = await checkRunnerWorker()
    if (problems.length > 0) {
      console.error('Runner worker is not usable:\n' + problems.map((line) => `  - ${line}`).join('\n'))
      process.exit(1)
    }
    console.log('Runner worker bundle verified.')
    return
  }
  await buildRunnerWorker()
}

if (process.argv[1] && path.resolve(process.argv[1]) === path.resolve(import.meta.filename)) {
  await main()
}
